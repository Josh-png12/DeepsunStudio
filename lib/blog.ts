import fs from 'fs'
import path from 'path'
import matter from 'gray-matter'

const BLOG_DIR = path.join(process.cwd(), 'content', 'blog')

export interface PostMeta {
  slug: string
  title: string
  description: string
  date: string
  readTime: string
  category: string
  /** Cover image path: `/blog-cover/<slug>` (generated) unless the front matter sets a local `cover`. */
  cover: string
}

/** A post with `draft: true` in its front matter stays in the repository but is not published anywhere (list, page, sitemap). */
const isDraft = (data: Record<string, unknown>) => data.draft === true

/**
 * Cover of a post. A front-matter `cover` is accepted only as a same-site path ("/…", not "//host", no "..");
 * anything else falls back to the brand cover generated by app/blog-cover/[slug]/route.tsx.
 */
export function resolveCover(slug: string, data: Record<string, unknown>): string {
  const c = data.cover
  if (typeof c === 'string' && /^\/(?![/\\])[^\s"'<>\\]*$/.test(c) && !c.includes('..')) return c
  return `/blog-cover/${slug}`
}

export function getAllPosts(): PostMeta[] {
  if (!fs.existsSync(BLOG_DIR)) return []
  return fs
    .readdirSync(BLOG_DIR)
    .filter((f) => f.endsWith('.mdx'))
    .flatMap((filename) => {
      const { data } = matter(fs.readFileSync(path.join(BLOG_DIR, filename), 'utf8'))
      if (isDraft(data)) return []
      return [
        {
          slug: filename.replace('.mdx', ''),
          title: data.title ?? filename,
          description: data.description ?? '',
          date: data.date ?? '',
          readTime: data.readTime ?? '5 min',
          category: data.category ?? 'General',
          cover: resolveCover(filename.replace('.mdx', ''), data),
        } satisfies PostMeta,
      ]
    })
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
}

export const getPublishedSlugs = () => getAllPosts().map((p) => p.slug)

export function getPost(slug: string) {
  const filePath = path.join(BLOG_DIR, `${slug}.mdx`)
  if (!fs.existsSync(filePath)) return null
  const { data, content } = matter(fs.readFileSync(filePath, 'utf8'))
  if (isDraft(data)) return null
  return { data, content }
}
