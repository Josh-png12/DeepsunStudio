import test from 'node:test'
import assert from 'node:assert/strict'
import { markdownToHtml } from '../lib/markdownToHtml.ts'
import { resolveCover } from '../lib/blog.ts'

test('a standalone local image becomes a lazy figure with caption, outside any paragraph', () => {
  const html = markdownToHtml('Intro.\n\n![Panel del bot](/blog/automatizar-whatsapp-negocio/panel.webp "El panel de respuestas")\n\nCierre.')
  assert.ok(
    html.includes(
      '<figure class="ds-fig"><img src="/blog/automatizar-whatsapp-negocio/panel.webp" alt="Panel del bot" loading="lazy" decoding="async" /><figcaption>El panel de respuestas</figcaption></figure>',
    ),
    html,
  )
  assert.ok(!/<p>[^]*<figure/.test(html.split('\n').find((l) => l.includes('<figure')) ?? ''), 'figure is not wrapped in <p>')
  assert.ok(html.includes('<p>Intro.</p>') && html.includes('<p>Cierre.</p>'))
  assert.ok(!html.includes('<a '), 'no link generated from image syntax')
})

test('caption is optional', () => {
  const html = markdownToHtml('![Captura](/blog/x/captura.webp)')
  assert.equal(html, '<figure class="ds-fig"><img src="/blog/x/captura.webp" alt="Captura" loading="lazy" decoding="async" /></figure>')
})

test('external, protocol-relative and non-/blog/ sources are rejected (no <img>, no <a>)', () => {
  for (const src of ['https://evil.example/x.webp', '//evil.example/x.webp', '/images/x.webp', 'javascript:alert(1)', '/blog//evil.example/x.webp']) {
    const html = markdownToHtml(`![x](${src})`)
    assert.ok(!html.includes('<img') && !html.includes('<a ') && !html.includes('evil'), `${src} → ${html}`)
  }
})

test('paths with .. are rejected', () => {
  const html = markdownToHtml('![x](/blog/../../etc/passwd.webp)')
  assert.ok(!html.includes('<img') && !html.includes('<a '), html)
})

test('alt text and caption are escaped (quotes, < and markdown never inject markup)', () => {
  const html2 = markdownToHtml('![a "b" <i>x</i> **c** & d](/blog/x/y.webp "pie <b>x</b> & más")')
  assert.ok(html2.includes('alt="a &quot;b&quot; &lt;i&gt;x&lt;/i&gt; **c** &amp; d"'), html2)
  assert.ok(html2.includes('<figcaption>pie &lt;b&gt;x&lt;/b&gt; &amp; más</figcaption>'), html2)
  assert.ok(!html2.includes('<strong>'), 'bold rule does not reach inside the alt')
})

test('an image in the middle of a sentence is dropped, never turned into a link', () => {
  const html = markdownToHtml('Mira esto ![x](/blog/x/y.webp) aquí.')
  assert.ok(!html.includes('<img') && !html.includes('<a '), html)
  assert.ok(html.startsWith('<p>Mira esto'))
})

test('regular links still work next to images', () => {
  const html = markdownToHtml('Lee [la guía](/blog/otra) primero.\n\n![x](/blog/x/y.webp)')
  assert.ok(html.includes('<a href="/blog/otra">la guía</a>'), html)
  assert.ok(html.includes('<img src="/blog/x/y.webp"'), html)
})

test('covers: generated by default, front-matter override only for same-site paths', () => {
  assert.equal(resolveCover('post', {}), '/blog-cover/post')
  assert.equal(resolveCover('post', { cover: '/blog/post/portada.webp' }), '/blog/post/portada.webp')
  for (const bad of ['https://evil.example/a.png', '//evil.example/a.png', '/blog/../x.png', 'portada.webp', '/a b.png', '/\\evil', 42]) {
    assert.equal(resolveCover('post', { cover: bad }), '/blog-cover/post', String(bad))
  }
})
